package llm

import (
	"context"
	"errors"
)

// Standard domain errors for LLM operations.
var (
	ErrNilRequest          = errors.New("llm: chat request cannot be nil")
	ErrEmptyMessages       = errors.New("llm: messages list cannot be empty")
	ErrMissingModel        = errors.New("llm: model name is required")
	ErrInvalidAPIKey       = errors.New("llm: api key is required")
	ErrProviderUnavailable = errors.New("llm: provider endpoint unavailable")
	ErrContextCanceled     = errors.New("llm: operation canceled by context")
	ErrMaxRetriesExceeded  = errors.New("llm: maximum retries exceeded")
	ErrStreamClosed        = errors.New("llm: completion stream unexpectedly closed")
	ErrInvalidToolCall     = errors.New("llm: invalid tool call format received from provider")
)

// Role defines the participant role in a conversation.
type Role string

const (
	RoleSystem    Role = "system"
	RoleUser      Role = "user"
	RoleAssistant Role = "assistant"
	RoleTool      Role = "tool"
)

// FunctionCall describes the function and serialized arguments generated by the model.
type FunctionCall struct {
	Name      string `json:"name"`
	Arguments string `json:"arguments"`
}

// ToolCall represents an explicit tool invocation by the LLM.
type ToolCall struct {
	ID       string       `json:"id"`
	Type     string       `json:"type"` // Defaults to "function"
	Function FunctionCall `json:"function"`
}

// ToolResult stores the execution result of a tool call.
type ToolResult struct {
	ToolCallID string `json:"tool_call_id"`
	Content    string `json:"content"`
	IsError    bool   `json:"is_error,omitempty"`
}

// ChatMessage represents a single message in a conversation.
type ChatMessage struct {
	Role       Role        `json:"role"`
	Content    string      `json:"content,omitempty"`
	ToolCalls  []ToolCall  `json:"tool_calls,omitempty"`
	ToolResult *ToolResult `json:"tool_result,omitempty"`
}

// NewUserMessage constructs a user chat message.
func NewUserMessage(content string) ChatMessage {
	return ChatMessage{
		Role:    RoleUser,
		Content: content,
	}
}

// NewSystemMessage constructs a system chat message.
func NewSystemMessage(content string) ChatMessage {
	return ChatMessage{
		Role:    RoleSystem,
		Content: content,
	}
}

// NewAssistantMessage constructs an assistant chat message.
func NewAssistantMessage(content string, toolCalls []ToolCall) ChatMessage {
	return ChatMessage{
		Role:      RoleAssistant,
		Content:   content,
		ToolCalls: toolCalls,
	}
}

// NewToolResultMessage constructs a tool result chat message.
func NewToolResultMessage(result ToolResult) ChatMessage {
	return ChatMessage{
		Role:       RoleTool,
		Content:    result.Content,
		ToolResult: &result,
	}
}

// ToolDefinition represents a tool schema exposed to the LLM.
type ToolDefinition struct {
	Name        string         `json:"name"`
	Description string         `json:"description,omitempty"`
	Parameters  map[string]any `json:"parameters"`
}

// ChatRequest structures a conversation inference request.
type ChatRequest struct {
	Model       string           `json:"model"`
	Messages    []ChatMessage    `json:"messages"`
	Tools       []ToolDefinition `json:"tools,omitempty"`
	Temperature *float64         `json:"temperature,omitempty"`
	TopP        *float64         `json:"top_p,omitempty"`
	MaxTokens   *int             `json:"max_tokens,omitempty"`
	Stop        []string         `json:"stop,omitempty"`
	ToolChoice  string           `json:"tool_choice,omitempty"`
}

// UsageMetrics quantifies token consumption for a request.
type UsageMetrics struct {
	PromptTokens     int `json:"prompt_tokens"`
	CompletionTokens int `json:"completion_tokens"`
	TotalTokens      int `json:"total_tokens"`
}

// ChatResponse encapsulates a structured completion response.
type ChatResponse struct {
	ID           string       `json:"id"`
	Model        string       `json:"model"`
	Message      ChatMessage  `json:"message"`
	FinishReason string       `json:"finish_reason"`
	Usage        UsageMetrics `json:"usage"`
}

// ChatChunk represents an incremental chunk in streaming mode.
type ChatChunk struct {
	ID           string        `json:"id"`
	Model        string        `json:"model"`
	DeltaContent string        `json:"delta_content"`
	DeltaTool    *ToolCall     `json:"delta_tool,omitempty"`
	FinishReason string        `json:"finish_reason,omitempty"`
	Usage        *UsageMetrics `json:"usage,omitempty"`
}

// LLMClient defines the agnostic interface for LLM completions.
type LLMClient interface {
	// ChatCompletion processes a synchronous conversation completion.
	ChatCompletion(ctx context.Context, req *ChatRequest) (*ChatResponse, error)

	// StreamChatCompletion opens a streaming subscription emitting chunks on channels.
	// The implementation guarantees that both channels are closed when streaming ends or ctx is canceled.
	StreamChatCompletion(ctx context.Context, req *ChatRequest) (<-chan ChatChunk, <-chan error)
}
